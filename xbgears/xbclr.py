#!/usr/bin/env python
"""
xbclr - Remove files generated by an XBeach model run.

Dry run by default: lists what would be removed. Use --yes to delete (or move).

What counts as "generated" (XBeach manual, output and boundary-condition chapters):
  * xboutput.nc (or the ncfilename of params.txt)    netCDF output
  * XBlog.txt, XBwarning.txt, XBerror.txt            run logs
  * E_*.bcf, q_*.bcf, ebcflist.bcf, qbcflist.bcf,
    other *.bcf                                       generated wave boundary series
  * dims.dat, xy.dat                                  Fortran output (outputformat = fortran)
  * <var>.dat, <var>_mean/_var/_min/_max.dat, hrms.dat   Fortran map output, <var> = any
                                                      XBeach output variable
  * point<NNN>.dat, rugau<NNN>.dat, drifter*.dat      point / runup gauge / drifter output
  * hotstart*.dat                                     hotstart output (writehotstart = 1)

Not touched: params.txt, scripts, figures, and anything in sub-folders unless --recursive.

Safety:
  * Every file named in params.txt (depfile, xfile, bcfile, zs0file, ...) and every file
    listed in a FILELIST bcfile is never removed, even if it matches a pattern.
  * wbctype / instat = reuse  -> the *.bcf files are input, so they are kept.
  * hotstart = 1              -> hotstart*.dat are input, so they are kept.
  * A folder without params.txt is not treated as an XBeach model.
"""

import argparse
import fnmatch
import shutil
import sys
from pathlib import Path

from .xbgen.keydb import SPACEVARS

LOGS = ["XBlog.txt", "XBwarning.txt", "XBerror.txt"]
BCF = ["E_*.bcf", "q_*.bcf", "ebcflist.bcf", "qbcflist.bcf", "*.bcf"]
FORTRAN = ["dims.dat", "xy.dat", "point[0-9][0-9][0-9].dat", "rugau[0-9][0-9][0-9].dat",
           "drifter*.dat"]
HOTSTART = ["hotstart*.dat"]

# XBeach output variable names (manual, partable_spaceparams.tab) -> <var>.dat files
OUTVARS_L = {v.lower() for v in SPACEVARS} | {"hrms"}
SUFFIXES = ("", "_mean", "_var", "_min", "_max")
OUTPUT_KEYS = {"ncfilename"}       # params.txt keys that name an output file, not an input
SKIP_DIRS = {".ipynb_checkpoints", ".git", "__pycache__"}


def read_params(model_dir: Path) -> dict:
    """key(lower) -> value of params.txt (comments after % removed, first occurrence wins)."""
    vals = {}
    p = Path(model_dir) / "params.txt"
    for line in p.read_text(errors="ignore").splitlines():
        s = line.split("%")[0].strip()
        if "=" in s:
            k, v = (x.strip() for x in s.split("=", 1))
            if k and " " not in k:
                vals.setdefault(k.lower(), v)
    return vals


def protected_files(model_dir: Path, par: dict) -> set:
    """Files that params.txt uses as input (resolved paths)."""
    refs = set()
    for k, v in par.items():
        if not v or k in OUTPUT_KEYS:
            continue
        f = model_dir / v
        if f.is_file():
            refs.add(f.resolve())
            # FILELIST bcfile: protect the files it lists as well
            if k == "bcfile":
                try:
                    lines = f.read_text(errors="ignore").split("\n")
                except OSError:
                    continue
                if lines and lines[0].strip().upper() == "FILELIST":
                    for ln in lines[1:]:
                        parts = ln.split()
                        if parts:
                            g = model_dir / parts[-1]
                            if g.is_file():
                                refs.add(g.resolve())
    return refs


def is_fortran_var(name: str) -> bool:
    """True for <var>.dat / <var>_mean.dat / ... with <var> an XBeach output variable."""
    if not name.endswith(".dat"):
        return False
    stem = name[:-4]
    for suf in SUFFIXES:
        if suf and stem.endswith(suf):
            if stem[: -len(suf)] in OUTVARS_L:
                return True
        elif not suf and stem in OUTVARS_L:
            return True
    return False


def find_generated(model_dir, keep_bc: bool = False):
    """
    List the generated files of one model folder.

    Returns:
        (found, notes): found = sorted [(Path, reason)], notes = [str]
    """
    model_dir = Path(model_dir)
    par = read_params(model_dir)
    refs = protected_files(model_dir, par)
    wbc = (par.get("wbctype") or par.get("instat") or "").lower()
    keep_bcf = keep_bc or wbc == "reuse"
    keep_hot = par.get("hotstart", "0").strip() in ("1", "1.0")

    patterns = [(p, "log") for p in LOGS]
    nc = par.get("ncfilename", "xboutput.nc")
    patterns += [(nc, "netCDF output"), ("xboutput.nc", "netCDF output")]
    if not keep_bcf:
        patterns += [(p, "wave boundary series") for p in BCF]
    patterns += [(p, "Fortran output") for p in FORTRAN]
    if not keep_hot:
        patterns += [(p, "hotstart output") for p in HOTSTART]

    found = []
    for f in model_dir.iterdir():
        if not f.is_file():
            continue
        if f.resolve() in refs or f.name.lower() == "params.txt":
            continue
        name = f.name.lower()
        why = next((f"{kind}, {pat}" for pat, kind in patterns
                    if fnmatch.fnmatch(name, pat.lower())), None)
        if why is None and is_fortran_var(name):
            why = "Fortran output, <var>.dat"
        if why:
            found.append((f, why))
    notes = []
    if wbc == "reuse":
        notes.append("wbctype = reuse -> *.bcf kept (input)")
    if keep_hot:
        notes.append("hotstart = 1 -> hotstart*.dat kept (input)")
    return sorted(found), notes


def model_dirs(root, recursive: bool = False):
    """Model folders (containing params.txt) at / below root."""
    root = Path(root)
    if not recursive:
        return [root]
    out = []
    for d in [root] + sorted(p for p in root.rglob("*") if p.is_dir()):
        if any(part in SKIP_DIRS for part in d.relative_to(root).parts):
            continue
        if (d / "params.txt").is_file():
            out.append(d)
    return out


def human(n: float) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024:
            return f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"


def clean_outputs(
    model_dir=".",
    yes=False,
    keep_bc=False,
    recursive=False,
    move_to=None,
):
    """
    Remove (or move) files generated by XBeach runs.

    Args:
        model_dir (str | Path): Model folder with params.txt (or root folder with recursive=True)
        yes (bool): Actually delete / move; False = dry run, only list
        keep_bc (bool): Keep generated wave boundary files (*.bcf)
        recursive (bool): Clean every folder below model_dir that contains a params.txt
        move_to (str | Path): Move files into this folder (relative to each model folder)
            instead of deleting

    Returns:
        list: [(model_dir, file, reason)] of the files found (and removed when yes=True)
    """
    root = Path(model_dir).resolve()
    if not root.is_dir():
        sys.exit(f"Error: not a folder: {root}")
    if not recursive and not (root / "params.txt").is_file():
        sys.exit(f"Error: no params.txt in {root} - is this an XBeach model folder? "
                 "(use -r for sub-folders)")
    dirs = model_dirs(root, recursive)
    if not dirs:
        sys.exit(f"Error: no XBeach model folder (params.txt) found below {root}")

    targets = []
    for d in dirs:
        found, notes = find_generated(d, keep_bc)
        for n in notes:
            print(f"Note ({d.name}): {n}")
        targets += [(d, f, why) for f, why in found]
    if not targets:
        print("Nothing to clean.")
        return targets

    total, current = 0, None
    for d, f, why in targets:
        if d != current:
            print(f"Model folder: {d}")
            current = d
        size = f.stat().st_size
        total += size
        print(f"  {f.name:<32} {human(size):>10}   ({why})")
    print(f"{len(targets)} file(s), {human(total)}")

    if not yes:
        print("\nDry run - nothing removed. Re-run with --yes to clean.")
        return targets

    errors = 0
    for d, f, _ in targets:
        try:
            if move_to:
                dest = Path(move_to)
                dest = dest if dest.is_absolute() else d / dest
                dest.mkdir(parents=True, exist_ok=True)
                shutil.move(str(f), str(dest / f.name))
            else:
                f.unlink()
        except OSError as e:
            errors += 1
            print(f"  ! could not remove {f}: {e}")
    action = f"moved to {move_to}" if move_to else "deleted"
    print(f"{len(targets) - errors} file(s) {action}." + (f" {errors} failed." if errors else ""))
    return targets


def main():
    parser = argparse.ArgumentParser(
        prog="xbclr",
        description="Remove files generated by an XBeach model run (dry run unless --yes)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  xbclr                                  # Dry run in the current folder: list what would be removed
  xbclr --yes                            # Actually delete
  xbclr path/to/model --yes              # Clean another model folder
  xbclr --keep-bc --yes                  # Keep the generated wave boundary files (*.bcf)
  xbclr --move-to _old_run --yes         # Move instead of delete
  xbclr D:/runs -r --yes                 # Every model folder below D:/runs
        """,
    )
    parser.add_argument("model_dir", nargs="?", default=".",
                        help="model folder with params.txt (default: current folder)")
    parser.add_argument("--yes", "-y", action="store_true",
                        help="actually delete (default is dry run)")
    parser.add_argument("--keep-bc", action="store_true",
                        help="keep generated wave boundary files (*.bcf), e.g. to rerun with wbctype = reuse")
    parser.add_argument("--recursive", "-r", action="store_true",
                        help="clean every folder below model_dir that contains a params.txt")
    parser.add_argument("--move-to", metavar="DIR",
                        help="move files into DIR (relative to each model folder) instead of deleting")
    args = parser.parse_args()

    clean_outputs(
        model_dir=args.model_dir,
        yes=args.yes,
        keep_bc=args.keep_bc,
        recursive=args.recursive,
        move_to=args.move_to,
    )


if __name__ == "__main__":
    main()
